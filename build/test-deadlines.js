// The deadline panel, and the vendored engine it computes from.
//
// The engine is one implementation with two surfaces: the TC portal at
// aaritransactions.com and the Hub. A second copy that anybody edits is a
// second answer to "when is inspection over", so vendor/deadline-engine.js is
// byte for byte the upstream file at the commit its header names, and this
// test recomputes the hash rather than trusting the header.
//
// The rest is the panel: a file that is not a TC engagement gets no panel at
// all, the three empty states are checked in the order a coordinator needs
// them (contract type before dates), and nothing on this screen writes.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const ENGINE = path.join(root, 'vendor', 'deadline-engine.js');
const TX = fs.readFileSync(path.join(root, 'tx_module.html'), 'utf8');

let fails = 0, checks = 0;
function ok(name, cond, detail) {
  checks++;
  if (cond) { console.log('  ok   ' + name); return; }
  fails++;
  console.log('  FAIL ' + name + (detail ? '\n       ' + detail : ''));
}

// ---------------------------------------------------------------- vendored copy
console.log('\nvendor/deadline-engine.js');
ok('the engine is vendored', fs.existsSync(ENGINE));
const src = fs.readFileSync(ENGINE, 'utf8');
const head = src.split('\n').slice(0, 22).join('\n');

const commit = (head.match(/Commit\s+([0-9a-f]{40})/) || [])[1];
const sha = (head.match(/sha256\s+([0-9a-f]{64})/) || [])[1];
ok('the header names the upstream commit', !!commit, 'no 40 character sha in the header');
ok('the header names the body hash', !!sha, 'no sha256 in the header');

// The body is everything after the vendoring header. If anybody patches the
// engine here instead of upstream, this hash stops matching and says so.
const body = src.split('\n').slice(22).join('\n');
const actual = crypto.createHash('sha256').update(Buffer.from(body, 'utf8')).digest('hex');
ok('the vendored body is unmodified', actual === sha,
   'header says ' + sha + '\n       file is   ' + actual +
   '\n       Fix the engine in aari-transactions-landing and re-pin, never here.');

ok('the header forbids editing here', /Do not edit this file/.test(head));

const ctx = { window: {}, console: { log(){}, error(){}, warn(){} } };
vm.createContext(ctx);
vm.runInContext(src, ctx);
const ENG = ctx.window.AariDeadlineEngine;
ok('it attaches the engine and nothing else',
   !!ENG && Object.keys(ctx.window).length === 1, Object.keys(ctx.window).join(', '));
ok('it exports fileContractDeadlines', !!ENG && typeof ENG.fileContractDeadlines === 'function');

// ------------------------------------------------------- the export honours _dates
console.log('\nthe fixed export');
const FILE = {
  id: 'test', service_type: 'tc_one_side', contract_type: 'frbar_asis',
  effective_date: '2026-01-05', closing_date: '2026-03-06',
  logistics: {}, raw_form_data: {},
};
const plain = ENG.fileContractDeadlines(FILE);
ok('a file with no _dates computes a schedule', plain.length > 0);
ok('and stamps nothing as edited', plain.every(r => !r.date_overridden));

const key = plain[1].key;
const edited = ENG.fileContractDeadlines(
  Object.assign({}, FILE, { deadline_overrides: { _dates: { [key]: '2026-02-14' } } }));
const row = edited.find(r => r.key === key);
ok('an absolute override replaces the computed date',
   row && ENG.ymd(row.date) === '2026-02-14', row && ENG.ymd(row.date));
ok('and is stamped date_overridden', !!(row && row.date_overridden));
ok('and only that row is stamped', edited.filter(r => r.date_overridden).length === 1);
ok('a day count override still shifts the computation',
   String(ENG.fileContractDeadlines(Object.assign({}, FILE, { logistics: { inspection_days: 20 } }))
     .find(r => r.key === 'inspection_end').date)
   !== String(plain.find(r => r.key === 'inspection_end').date));
ok('an unparseable override leaves the computed date alone',
   (function(){
     const j = ENG.fileContractDeadlines(
       Object.assign({}, FILE, { deadline_overrides: { _dates: { [key]: 'garbage' } } }))
       .find(r => r.key === key);
     return !j.date_overridden && String(j.date) === String(plain[1].date);
   })());
ok('rows carry the paragraph citation', plain.every(r => typeof r.citation === 'string'));

// ---------------------------------------------------------------- the panel
console.log('\nthe deadline panel in tx_module.html');
ok('the engine is served from our own origin',
   /CTR_ENGINE_SRC = '\/vendor\/deadline-engine\.js'/.test(TX));
ok('nothing still pulls the engine cross origin',
   !/aaritransactions\.com\/js\/deadline-engine\.js/.test(TX));
ok('a failed load is reported, not swallowed',
   /sc\.onerror = function\(\)\{ CTR_ENG_ERR/.test(TX));
ok('the file row carries what the engine reads',
   ['service_type', 'contract_type', 'effective_date', 'closing_date', 'logistics', 'deadline_overrides']
     .every(c => new RegExp("select\\('id[^']*" + c).test(TX)));

// The panel functions, lifted out and run for real rather than grepped.
const slice = TX.slice(TX.indexOf("var CTR_ENGINE_SRC ="), TX.indexOf('async function ctrLoadRail('));
ok('the panel source was found', slice.length > 400);
const T = {
  deadlines: 'Deadlines', dl_edited: 'edited',
  dl_notype: 'Pick a contract type to compute deadlines.',
  dl_nodates: 'Enter both Effective and Closing dates to compute deadlines.',
  dl_norows: 'No deadlines for this contract type.',
  dl_noengine: 'The deadline engine did not load,',
  dl_failed: 'The deadline engine could not compute this schedule:',
  dl_roll_a: 'Fell on ', dl_roll_b: ' · Standard F moved it to the next business day.',
};
const pctx = {
  window: { AariDeadlineEngine: ENG },
  document: null,
  CTR_LANG: 'en',
  esc: (v) => String(v == null ? '' : v),
  ctrT: (k) => T[k],
  console,
};
vm.createContext(pctx);
vm.runInContext(slice, pctx);
const panel = (f) => pctx.ctrDeadlinesHtml(f);

ok('an mls_setup file gets no panel at all',
   panel(Object.assign({}, FILE, { service_type: 'mls_setup' })) === '');
ok('a file_organization file gets no panel at all',
   panel(Object.assign({}, FILE, { service_type: 'file_organization' })) === '');
ok('a file with no service_type gets no panel at all',
   panel(Object.assign({}, FILE, { service_type: null })) === '');
ok('the tc spelling gets a panel', panel(Object.assign({}, FILE, { service_type: 'tc' })) !== '');
ok('the tc_one_side spelling gets a panel', panel(FILE) !== '');

// Guard order: a TC file missing both a type and the dates must name the type,
// because that is the field to go and fill in first.
const noType = panel(Object.assign({}, FILE, { contract_type: null, effective_date: null }));
ok('no contract type says so, dates or not', noType.indexOf(T.dl_notype) !== -1);
ok('and does not send the coordinator to the date fields',
   noType.indexOf(T.dl_nodates) === -1);
ok('a missing effective date says both dates',
   panel(Object.assign({}, FILE, { effective_date: null })).indexOf(T.dl_nodates) !== -1);
ok('a missing closing date says both dates',
   panel(Object.assign({}, FILE, { closing_date: null })).indexOf(T.dl_nodates) !== -1);
ok('a contract type with no rows says so',
   panel(Object.assign({}, FILE, { contract_type: 'not_a_real_form' })).indexOf(T.dl_norows) !== -1);

const html = panel(FILE);
ok('every row names its deadline', plain.every(r => html.indexOf(r.name) !== -1));
ok('the citations are on screen',
   plain.filter(r => r.citation).every(r => html.indexOf(r.citation.slice(0, 40)) !== -1));
// A schedule whose arithmetic actually lands on a weekend, so the roll line has
// something to say. Found rather than assumed: the sample above happens not to
// roll, and a test that asserts on a date nobody checked is not a test.
let rollFile = null, rollRows = null;
for (let d = 1; d <= 28 && !rollFile; d++) {
  const f = Object.assign({}, FILE, { effective_date: '2026-01-' + String(d).padStart(2, '0') });
  const rs = ENG.fileContractDeadlines(f);
  if (rs.some(r => r.computedDate && r.date && r.computedDate.getTime() !== r.date.getTime())) {
    rollFile = f; rollRows = rs;
  }
}
ok('a schedule that rolls off a weekend exists to test with', !!rollFile);
const rollHtml = panel(rollFile);
ok('a rolled date states the roll', rollHtml.indexOf(T.dl_roll_b) !== -1);
ok('it names the day it fell on',
   rollRows.filter(r => r.computedDate.getTime() !== r.date.getTime())
     .every(r => rollHtml.indexOf(T.dl_roll_a + pctx.ctrDlDate(r.computedDate)) !== -1));
ok('and only the rows that rolled say so',
   (rollHtml.match(/ctr-dlr/g) || []).length ===
   rollRows.filter(r => r.computedDate && r.date && r.computedDate.getTime() !== r.date.getTime()).length);
ok('a schedule with no roll claims none', (html.match(/ctr-dlr/g) || []).length ===
   plain.filter(r => r.computedDate && r.date && r.computedDate.getTime() !== r.date.getTime()).length);

const editedHtml = panel(
  Object.assign({}, FILE, { deadline_overrides: { _dates: { [key]: '2026-02-14' } } }));
ok('an edited date carries the marker', editedHtml.indexOf('>edited<') !== -1);
ok('and only on that one row', (editedHtml.match(/>edited</g) || []).length === 1);
ok('an edited date does not also claim a roll',
   editedHtml.split('<div class="ctr-dl">')
     .filter(b => b.indexOf('>edited<') !== -1)
     .every(b => b.indexOf('ctr-dlr') === -1));

// The engine failing to load must not look like a file without deadlines.
const dark = vm.createContext({
  window: {}, document: null, CTR_LANG: 'en',
  esc: pctx.esc, ctrT: pctx.ctrT, console,
});
vm.runInContext(slice, dark);
const darkHtml = dark.ctrDeadlinesHtml(FILE);
ok('no engine reads as a failure, not an empty schedule',
   darkHtml.indexOf(T.dl_noengine) !== -1 && darkHtml.indexOf('ctr-note err') !== -1);

// ---------------------------------------------------------------- read only
console.log('\nread only');
ok('the panel writes nothing',
   !/\.(update|insert|upsert|delete)\s*\(/.test(slice));
ok('the panel reads no payment column',
   !/payment_status|payment_confirmed|paid_at|amount_paid_cents|invoice_id/.test(slice));
ok('the contracts rail reads no payment column',
   !/select\('id[^']*(payment_status|payment_confirmed|paid_at|amount_paid_cents|invoice_id)/.test(TX));

console.log('\n' + (fails ? fails + ' of ' + checks + ' checks FAILED' : checks + ' checks passed'));
process.exit(fails ? 1 : 0);
